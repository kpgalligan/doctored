import Foundation

extension AgentServer {
    /// `load_files_into_stack`, `auto_align_layers`, `stack_mode` and
    /// `reduce_noise_from_stack` (AgentServer+Stacks.swift).
    @inline(never) func stacksCatalog() -> [[String: Any]] {
        let load = [
            "Load several image files as the layers of ONE new document — File ▸ Load Files ",
            "into Stack…. paths lists at least 2 absolute file paths of any type open_document ",
            "reads (a camera RAW takes its default development; a PDF or SVG its first page at ",
            "300 ppi; a PSD or layered TIFF its flattened composite); a Doctored .doctored document ",
            "is refused by name. Each file becomes one raster layer named after its file ",
            "(extension dropped), bottom-first in paths order, and the same path may appear ",
            "twice. The canvas is the largest width and the largest height among the files; a ",
            "smaller file sits at the top-left, unscaled, with transparency beside it. The ",
            "document takes what File ▸ Open gives the FIRST file: its depth (8, 16 or 32-bit ",
            "float), its profile and, for an 8-bit open, the conversion into the working space. ",
            "Every later file is converted to that depth and profile exactly as place_image ",
            "converts a placed file. The whole stack's working memory is planned and checked ",
            "before any file is decoded, so a refusal opens nothing. The new document is ",
            "untitled (or takes name), unsaved, with an empty history and its top layer active. ",
            "Reply: {ok, document, depth: \"rgba8\"|\"rgba16\"|\"rgba32_float\", profile, ",
            "canvas: {width, height}, layers: [{index, name, path, width, height, source_depth ",
            "(8, 16 or 32), converted_depth, converted_profile, disclosures?}], ",
            "working_memory_plan_bytes, note?} — note says which files were converted and ",
            "repeats anything a file's own open disclosed. Not recorded into Actions.",
        ].joined()
        let align = [
            "Register raster layers to a reference layer, warp each into place and grow the ",
            "canvas to hold them — Edit ▸ Auto-Align Layers…. layers names at least 2 layer ",
            "indices; each must be a raster layer (not a group, an adjustment layer, or a ",
            "text, shape or fill layer) that is not linked to another layer. The reference ",
            "stays where it is: reference when given (it must be one of layers), else the one ",
            "layer among them that is position-locked, else the lowest index — the bottom ",
            "layer. Any other position-locked layer is refused by name. ",
            "projection is the dialog's choice (default auto): \"auto\" and \"perspective\" ",
            "(the same: a translation, then a homography on the layer shifted by it, or the ",
            "translation alone when the two disagree or, failing both, a homography alone; ",
            "or, when Vision finds nothing or its answer disagrees with the core's feature ",
            "matches, the homography of those matches); ",
            "\"collage\" (that answer reduced to rotation, uniform scale and shift, no ",
            "perspective, else the translation or the matched features' own similarity, ",
            "whichever the layers' edges agree with better); \"reposition\" (a translation ",
            "only: Vision's or the matched features' mean shift, the same way); ",
            "\"cylindrical\" and \"spherical\" (each layer registered as perspective does, ",
            "on the original frames; one focal length and a rotation per layer fitted to those ",
            "maps; then EVERY layer, the reference too, reprojected by the core onto the ",
            "reference camera's cylinder or sphere at that focal, and the canvas set to the ",
            "union of the projected layers, which may also shrink it). With cylindrical or ",
            "spherical: a layer only a translation registers is tried once against the ",
            "registered layer nearest in index, else listed in unregistered and left alone; ",
            "layers that do not turn about one point (a pure shift, identical layers) or ",
            "that no perspective registration matches (frames overlapping too little or too ",
            "widely) are refused (\"The layers do not turn about one point, or they overlap ",
            "too little or too widely to align…\") ",
            "and nothing changes; any position-locked layer, the reference included, and a ",
            "placed image are refused by name; sampler must be bicubic. vignette (default ",
            "false) is the dialog's Lens Correction ▸ Vignette Removal: one radial falloff ",
            "V = 1 + a·ρ² (ρ a pixel's distance from its layer's centre over the farthest ",
            "pixel centre, one a for the whole stack) is fitted in linear light to the ",
            "registered overlaps and every layer is multiplied by gain / V, gain the mean of V ",
            "over every layer's pixels, before the layers are reprojected; with auto or ",
            "perspective it reprojects onto the sphere, as spherical does, ",
            "cylindrical and spherical keep their surface, and collage and ",
            "reposition ignore it (no vignette reply); sampler must be ",
            "bicubic when it reprojects, and layers that overlap too little to measure the ",
            "falloff are refused. distortion (default false) is the dialog's Lens Correction ",
            "▸ Geometric Distortion: one radial lens coefficient k for the whole stack (a ",
            "layer pixel p shows the undistorted point u with p = c + R·q·(1 + k·|q|²), q = ",
            "(u − c)/R, c the layer's centre, R half its longer side, k in −0.25…0.25) is ",
            "fitted from patch matches in the registered overlaps, the registration is ",
            "refined between the corrected layers, and every layer is reprojected with the ",
            "lens undone; with auto or perspective it reprojects onto the sphere, cylindrical ",
            "and spherical keep their surface, and collage and reposition correct each layer, ",
            "the reference too, within its own frame (it keeps its size) before the ",
            "similarity or translation places it, with no surface in the reply; ",
            "there any position-locked layer and a placed image are refused by name, ",
            "and a stack in which no layer moves is refused (\"Geometric Distortion needs a ",
            "layer that moves against the reference…\"). sampler must be bicubic ",
            "with distortion, and layers that overlap too little to measure the lens are ",
            "refused. The older ",
            "registration (\"auto\" | \"translation\") is still read when projection is ",
            "absent; passing both is refused. Vision, then the core's feature matching, ",
            "register on frames no larger than 2048 ",
            "pixels on their longest side, and the core's perspective transform resamples the ",
            "layer with sampler (default bicubic). A registration is used only when the two ",
            "layers' edges then coincide; otherwise the layer is left untouched and listed in ",
            "unregistered — expect that for a layer that shares less than about a quarter of ",
            "the frame with the reference (a pure shift: about 15 %), or one that shows ",
            "something else. Layers whose frames carry lens distortion are listed with ",
            "\"the frames carry lens distortion; turn on Geometric Distortion\" unless ",
            "distortion is true, and when no layer registers for that reason cylindrical ",
            "and spherical refuse with the same sentence. When an ",
            "aligned layer reaches past the canvas, the canvas grows (as reveal_canvas grows ",
            "it) to the union of the canvas, the reference and every aligned layer, and the ",
            "selection moves with it; a union past 100 megapixels (or past the alpha channels' ",
            "budget) is refused by a sentence and nothing changes. The reference, the layer ",
            "order and the selected layers do not change; the area a warp leaves uncovered is ",
            "transparent. One history step for the warps and the canvas together; the job ",
            "shows progress and can be cancelled. A reference with no opaque pixels is ",
            "refused. Reply: {ok, changed, projection, reference, aligned: [{layer, name, ",
            "method: \"homography\"|\"similarity\"|\"translation\", homography (9 numbers, ",
            "row-major 3×3 in canvas pixels of the canvas before it grew, origin top-left, y ",
            "down: where a point of the layer belongs in the reference), quad ([[x, y] × 4]: ",
            "where the layer's rectangle went, same coordinates, top-left, top-right, ",
            "bottom-right, bottom-left)}], unchanged: [{layer, name}] (already within 0.1 ",
            "pixel), unregistered: [{layer, name, reason}] (left untouched: no pixels, no ",
            "registration matched the reference, or the core refused the warp), canvas? ",
            "({width, height, origin: {x, y}}: present only when the canvas changed; origin ",
            "is where the old canvas's top-left sits in the new one), registration_plan_bytes, ",
            "focal? and each aligned row's rotation? (cylindrical and spherical only: the focal ",
            "length in canvas pixels, and 9 numbers, row-major 3×3, taking a ray of the ",
            "reference camera to the same ray of the layer's camera), surface? (\"cylindrical\" ",
            "| \"spherical\": the surface whenever the job reprojected), vignette? ({coefficient ",
            "(a), gain, samples (the overlap ratios measured), layers}: when vignette ran), ",
            "distortion? ({coefficient (k), matches (the patch matches kept), residual (their ",
            "RMS transfer error, pixels), layers}: with distortion true; with distortion, ",
            "aligned homographies map corrected points), ",
            "working_memory_plan_bytes, document}. Works at 8, 16 and 32 bits and in CMYK.",
        ].joined()
        let stack = [
            "Compute one per-pixel statistic across raster layers into ONE new raster layer — ",
            "Layer ▸ Stack Mode. layers names at least 2 layer indices, each a raster layer (not ",
            "a group or an adjustment layer); mode is one of entropy, kurtosis, majority, ",
            "maximum, mean, median, minimum, range (maximum − minimum), skewness, ",
            "standard_deviation (population), summation or variance. The new layer covers the ",
            "union of the layers' pixel rectangles and lands directly above the topmost of the ",
            "layers given, at that layer's level, named name (default: the mode's title, e.g. ",
            "\"Median\"); it becomes the active layer. The layers read are kept and hidden; ",
            "nothing else changes. Per pixel: a layer is transparent outside its own rectangle; ",
            "the layers with alpha above 0 there are the ones present, and none leaves the ",
            "pixel transparent. The result's alpha is the largest alpha present. mean is each ",
            "colour channel's alpha-weighted mean over the layers present. Every other mode ",
            "reads the layers at least half covered there (all the present ones when none is), ",
            "unweighted: median is the middle value, or the mean of the two middle values. ",
            "With F white (255, 65535 or 1.0) and n the layers read: summation is the sum ",
            "(clamped to white at 8 and 16 bits); variance is the population variance divided ",
            "by F; skewness is F/2 × (1 + s / s_max) and kurtosis F × (k − 1) / (k_max − 1), ",
            "each scaled by the largest value n layers can reach (one layer apart from the ",
            "rest) so both span black to white — a symmetric or two-layer sample reads ",
            "skewness F/2 and kurtosis 0; entropy is the base-2 entropy of the values over 256 ",
            "equal bins of black to white, over log₂ min(n, 256), × F; majority is the most ",
            "frequent value, a tie taking the median of the tied values. Skewness, kurtosis ",
            "and entropy are fractions of white. ",
            "Statistics are of the stored values: 8- and 16-bit codes in the document's own ",
            "encoding (rounded half up), linear values at 32-bit float, where values above ",
            "white and below zero are kept. In a CMYK document the statistic runs per ink on ",
            "the inverted ink (65535 − ink, so minimum is the least ink and maximum the most) ",
            "and the new layer is in ink. Masks, opacity, blend modes and layer styles are ",
            "not read. The layers are NOT aligned first: use auto_align_layers before, or ",
            "reduce_noise_from_stack. One history step; the job shows progress and can be ",
            "cancelled. Reply: {ok, layer (the new layer's index), name, mode, layers (the ",
            "layers read), hidden (those of them that were visible), ",
            "working_memory_plan_bytes, document}. Works at 8, 16 and 32 bits and in CMYK.",
        ].joined()
        let denoise = [
            "Auto-align raster layers and combine them into ONE new raster layer that keeps ",
            "the picture and averages away the noise — Layer ▸ Reduce Noise from Stack…. ",
            "layers names at least 2 layer indices of frames of one scene, each a raster layer ",
            "(not a group, an adjustment layer, or a text, shape or fill layer) that is not ",
            "linked; mode is median (rejects what moves between frames) or mean (averages ",
            "noise best). The layers are first registered and warped exactly as ",
            "auto_align_layers does with projection \"auto\" and sampler \"bicubic\" (the ",
            "reference is the one position-locked layer among them, else the lowest index), ",
            "except that the canvas never grows, ",
            "then the statistic is taken as stack_mode takes it across the reference and every ",
            "layer that aligned. A layer no registration matched is listed in excluded and ",
            "left untouched: not warped, not read, not hidden. Fewer than two usable layers is ",
            "refused by a sentence naming the layers left out, and nothing changes. The new ",
            "layer, \"Noise Reduced\", lands directly above the topmost of the layers GIVEN — ",
            "an excluded one included, so it is never under a layer it left out — and becomes ",
            "the active layer; the layers read are hidden. One history step for the warps and ",
            "the new layer together; one job with progress that can be cancelled. Reply: {ok, ",
            "layer (the new layer's index), name, mode, reference, layers (the layers the ",
            "statistic read), hidden (those of them that were visible), aligned: [{layer, ",
            "name, method: \"homography\"|\"translation\"}], unchanged: [{layer, name}] ",
            "(already within 0.1 pixel), excluded: [{layer, name, reason}], ",
            "registration_plan_bytes, working_memory_plan_bytes, document}. Works at 8, 16 and ",
            "32 bits and in CMYK.",
        ].joined()
        return [
            tool("load_files_into_stack", load,
                 [
                    "paths": [
                        "type": "array", "items": ["type": "string"],
                        "minItems": StackLoad.minimumFiles,
                        "description": "Absolute file paths, bottom layer first.",
                    ] as [String: Any],
                    "name": ["type": "string", "description": "The new document's title."],
                 ], required: ["paths"]),
            tool("auto_align_layers", align,
                 [
                    "layers": ["type": "array", "items": ["type": "integer"], "minItems": 2],
                    "reference": [
                        "type": "integer",
                        "description": "The layer that stays put; one of layers.",
                    ] as [String: Any],
                    "projection": [
                        "type": "string",
                        "enum": AutoAlign.Registration.projections.map(\.projectionName),
                        "default": "auto",
                    ] as [String: Any],
                    "registration": [
                        "type": "string", "enum": ["auto", "translation"],
                        "description": "The older spelling, read when projection is absent.",
                    ] as [String: Any],
                    "sampler": [
                        "type": "string", "enum": ["nearest", "bilinear", "bicubic", "lanczos"],
                        "default": "bicubic",
                    ] as [String: Any],
                    "vignette": [
                        "type": "boolean", "default": false,
                        "description": "Lens Correction ▸ Vignette Removal.",
                    ] as [String: Any],
                    "distortion": [
                        "type": "boolean", "default": false,
                        "description": "Lens Correction ▸ Geometric Distortion.",
                    ] as [String: Any],
                    "document_id": Self.docIDProperty,
                 ], required: ["layers"]),
            tool("stack_mode", stack,
                 [
                    "layers": ["type": "array", "items": ["type": "integer"], "minItems": 2],
                    "mode": [
                        "type": "string", "enum": StackMode.allCases.map(\.rawValue),
                    ] as [String: Any],
                    "name": ["type": "string", "description": "The new layer's name."],
                    "document_id": Self.docIDProperty,
                 ], required: ["layers", "mode"]),
            tool("reduce_noise_from_stack", denoise,
                 [
                    "layers": ["type": "array", "items": ["type": "integer"], "minItems": 2],
                    "mode": [
                        "type": "string", "enum": StackMode.noiseModes.map(\.rawValue),
                    ] as [String: Any],
                    "document_id": Self.docIDProperty,
                 ], required: ["layers", "mode"]),
        ]
    }
}
