#!/usr/bin/env python3
"""Generate the public MCP tool reference from Doctored's tool catalog.

Exactly one source: `--socket PATH`, a running instance's agent socket (its
`DR_AGENT_SOCKET`; the live `tools/list`), or `--catalog FILE`, a built bundle's
`Contents/Resources/agent-catalog.json` (the snapshot the build writes, with no
app running). Both are rendered from the same key order (sorted, as the core's
JSON already is), so the two give the same page for the same build.
"""

import argparse
import json
from pathlib import Path
import sys

from mcp_client import Client


DEFAULT_OUTPUT = Path("public-docs/src/content/docs/reference/mcp-tools.md")


def fetch_tools(socket_path: str) -> list[dict]:
    reply = Client(socket_path).post(
        {"jsonrpc": "2.0", "id": 1, "method": "tools/list", "params": {}}
    )
    if reply is None or "error" in reply:
        raise RuntimeError(json.dumps(reply and reply["error"], sort_keys=True))
    return reply["result"]["tools"]


def read_catalog(path: Path) -> list[dict]:
    tools = json.loads(path.read_text())["tools"]
    if not isinstance(tools, list):
        raise RuntimeError(f"{path} has no tools array")
    return tools


def canonical(tools: list[dict]) -> list[dict]:
    """`tools` with every object's keys in sorted order: the order the page renders in."""
    return json.loads(json.dumps(tools, sort_keys=True))


def markdown_text(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def schema_type(schema: dict) -> str:
    kind = schema.get("type", "any")
    if kind == "array":
        return f"array<{schema_type(schema.get('items', {}))}>"
    return str(kind)


def schema_constraints(schema: dict) -> str:
    parts = []
    if "enum" in schema:
        parts.append("one of " + ", ".join(f"`{value}`" for value in schema["enum"]))
    if "const" in schema:
        parts.append(f"must be `{schema['const']}`")
    if "default" in schema:
        parts.append(f"default `{schema['default']}`")
    if "minimum" in schema or "maximum" in schema:
        low = schema.get("minimum", "−∞")
        high = schema.get("maximum", "∞")
        parts.append(f"{low}–{high}")
    if "exclusiveMinimum" in schema:
        parts.append(f"> {schema['exclusiveMinimum']}")
    if "minItems" in schema or "maxItems" in schema:
        low = schema.get("minItems", 0)
        high = schema.get("maxItems", "unbounded")
        parts.append(f"{low}–{high} items")
    if schema.get("uniqueItems"):
        parts.append("unique items")
    if schema.get("additionalProperties") is False:
        parts.append("no extra properties")
    items = schema.get("items", {})
    item_parts = []
    if "enum" in items:
        item_parts.append("one of " + ", ".join(f"`{value}`" for value in items["enum"]))
    if "minimum" in items or "maximum" in items:
        low = items.get("minimum", "−∞")
        high = items.get("maximum", "∞")
        item_parts.append(f"{low}–{high}")
    if "exclusiveMinimum" in items:
        item_parts.append(f"> {items['exclusiveMinimum']}")
    if item_parts:
        parts.append("items: " + "; ".join(item_parts))
    return "; ".join(parts) or "—"


def argument_rows(properties: dict, required: set[str], prefix: str = "") -> list[tuple]:
    rows = []
    for argument, argument_schema in properties.items():
        path = f"{prefix}.{argument}" if prefix else argument
        requirement = "yes" if argument in required else "no"
        if prefix and requirement == "yes":
            requirement = "with parent"
        rows.append((path, argument_schema, requirement))

        nested_schema = argument_schema
        nested_prefix = path
        if argument_schema.get("type") == "array":
            nested_schema = argument_schema.get("items", {})
            nested_prefix += "[]"
        nested_properties = nested_schema.get("properties", {})
        if nested_properties:
            rows.extend(
                argument_rows(
                    nested_properties,
                    set(nested_schema.get("required", [])),
                    nested_prefix,
                )
            )
    return rows


def render(tools: list[dict]) -> str:
    lines = [
        "---",
        "title: MCP tool reference",
        "description: Every MCP tool exposed by Doctored, with its arguments and constraints.",
        "eyebrow: Reference",
        "tableOfContents: false",
        "---",
        "",
        "<!-- Generated by scripts/generate_mcp_reference.py. Do not edit by hand. -->",
        "",
        "An MCP client reaches Doctored through `doctored-mcp`, a stdio MCP server bundled",
        "inside the app at `Doctored.app/Contents/Helpers/doctored-mcp`. **Settings ▸ MCP**",
        "shows its path and copies the command that adds it to Claude Code",
        "(`claude mcp add --scope user doctored -- '<path>'`). The helper answers `initialize`",
        "and `ping` itself, lists tools from the running app (or, when none is running, from",
        "the catalog bundled with it), and opens Doctored in the background on the first",
        "tool call that finds it not running.",
        "",
        "The helper reaches the app over a Unix socket the app binds at every launch,",
        "`~/Library/Application Support/Doctored/Agent/agent.sock`, in a folder only its",
        "owner can open; `DR_AGENT_SOCKET` names another path for both. There is no TCP",
        "endpoint.",
        "",
        f"This build exposes **{len(tools)} tools**. The reference is generated from the app's",
        "`tools/list` catalog (live, or the snapshot the build writes from the same code),",
        "which is authoritative. Tool results are MCP",
        "content blocks; most calls return a JSON object in a text block, while `render` and",
        "some inspection calls can also return image blocks. Tool failures set `isError: true`",
        "and include a readable message.",
        "",
        "Regenerate this page from a running instance's socket, or from a built bundle's",
        "catalog with no app running:",
        "",
        "```sh",
        "python3 scripts/generate_mcp_reference.py --socket <the instance's DR_AGENT_SOCKET>",
        "python3 scripts/generate_mcp_reference.py --catalog Doctored.app/Contents/Resources/agent-catalog.json",
        "```",
        "",
        "Add `--check` to either to verify that the checked-in page matches the catalog.",
        "",
        "## All tools",
        "",
    ]
    lines.extend(f"- [`{tool['name']}`](#{tool['name']})" for tool in tools)

    for tool in tools:
        name = tool["name"]
        description = str(tool.get("description", "")).strip()
        schema = tool.get("inputSchema", {})
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        lines.extend(["", f"## `{name}`", "", description or "No description provided."])
        if not properties:
            lines.extend(["", "Takes no arguments."])
            continue
        lines.extend(
            [
                "",
                "| Argument | Type | Required | Constraints | Description |",
                "| :--- | :--- | :---: | :--- | :--- |",
            ]
        )
        for argument, argument_schema, requirement in argument_rows(properties, required):
            lines.append(
                "| `{}` | `{}` | {} | {} | {} |".format(
                    markdown_text(argument),
                    markdown_text(schema_type(argument_schema)),
                    requirement,
                    markdown_text(schema_constraints(argument_schema)),
                    markdown_text(argument_schema.get("description", "—")),
                )
            )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--socket", help="a running instance's agent socket (live tools/list)")
    source.add_argument("--catalog", type=Path,
                        help="a bundle's Contents/Resources/agent-catalog.json")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit nonzero instead of writing when the output is stale",
    )
    arguments = parser.parse_args()

    tools = fetch_tools(arguments.socket) if arguments.socket else read_catalog(arguments.catalog)
    content = render(canonical(tools))
    if arguments.check:
        if not arguments.output.exists() or arguments.output.read_text() != content:
            print(f"MCP reference is stale: {arguments.output}", file=sys.stderr)
            return 1
        print(f"MCP reference is current: {arguments.output}")
        return 0

    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(content)
    print(f"Wrote {arguments.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
