#!/usr/bin/env python3
"""Qualify Phase 9D retouch sampling against an actual Release app.

Fixtures are generated by scripts/retouch-probe/fixtures.py and are
self-contained: no camera or movie original is needed, because 9D adds no
source kind. This driver exercises what 9D adds — the three sampling modes,
the ignore-adjustments control, output to a new retouch layer, and the
compatibility rules — end to end, through the external MCP boundary only.

All outputs stay in private scratch. --require-current is the final gate; an
exploratory snapshot may report changed checkout inputs.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
import tempfile

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
PROBES = ROOT / 'scripts/retouch-probe'
sys.path.insert(0, str(PROBES))
import app_under_test
from support import HostApp


def digest(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def dependencies():
    paths = [*(ROOT / 'app/Sources').glob('*.swift'), *(ROOT / 'app/Bridging').glob('*.h'),
             *(ROOT / 'core/src').rglob('*.rs'), *(ROOT / 'core/tests').rglob('*.rs'),
             *(ROOT / 'core/include').glob('*.h'), *PROBES.glob('*.py'),
             ROOT / 'core/Cargo.toml', ROOT / 'core/Cargo.lock', ROOT / 'Makefile',
             ROOT / 'project.yml', ROOT / 'app/Info.plist', Path(__file__).resolve(),
             ROOT / 'scripts/phase5_support.py', ROOT / 'scripts/verification_isolation.py',
             ROOT / 'scripts/app_under_test.py',
             ROOT / 'scripts/verify_phase1.py', ROOT / 'scripts/verify_phase2.py',
             ROOT / 'scripts/verify_phase8b.py',
             ROOT / 'scripts/precision-probe/fixtures.py',
             ROOT / 'scripts/precision-probe/retained_fixtures.py',
             ROOT / 'scripts/precision-probe/retained_linked_fixtures.py',
             ROOT / 'scripts/host-source-probe/support.py',
             ROOT / 'scripts/live-filter-probe/native.py',
             ROOT / 'scripts/raw-probe/native.py',
             ROOT / 'scripts/generate_mcp_reference.py']
    return {str(path.relative_to(ROOT)): digest(path) for path in sorted(set(paths))}


def write(path, value):
    Path(path).write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixtures', type=Path, default=Path('/tmp/rz-phase9d-fixtures'))
    parser.add_argument('--app', type=Path,
                        default=app_under_test.default_app_executable())
    parser.add_argument('--require-current', action='store_true')
    parser.add_argument('--report', type=Path, required=True)
    arguments = parser.parse_args()

    fixtures = arguments.fixtures.resolve()
    if not fixtures.exists():
        spec = importlib.util.spec_from_file_location('phase9d_build_fixtures', PROBES / 'fixtures.py')
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        module.build(fixtures)
    folder = Path(tempfile.mkdtemp(prefix='rasterize-phase9d-retouch-'))
    print('Retouch-sampling qualification scratch:', folder, flush=True)
    before = dependencies()
    write(folder / 'source-provenance.json', before)
    fixture_hashes = {str(path.relative_to(fixtures)): digest(path)
                      for path in sorted(fixtures.rglob('*')) if path.is_file()}
    report = {'passed': False, 'scratch': str(folder), 'fixture_hashes': fixture_hashes,
              'app_sha256': digest(arguments.app)}
    try:
        spec = importlib.util.spec_from_file_location('phase9d_mcp', PROBES / 'mcp.py')
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        report['mcp'] = module.run(fixtures, folder / 'mcp', arguments.app.resolve())
        assert report['mcp']['passed']
        assert digest(arguments.app) == report['app_sha256'], 'Release app changed during qualification'
        after = dependencies()
        changed = sorted(name for name in before.keys() | after.keys()
                         if before.get(name) != after.get(name))
        report['source_check'] = {'files': len(before),
                                  'file_set_exact': before.keys() == after.keys(),
                                  'changes': changed}
        current = {str(path.relative_to(fixtures)): digest(path)
                   for path in sorted(fixtures.rglob('*')) if path.is_file()}
        report['fixture_file_set_and_hashes_exact'] = current == fixture_hashes
        assert current == fixture_hashes, 'Shared fixture file set or samples changed'
        if arguments.require_current:
            assert not changed and report['source_check']['file_set_exact'], changed
        report['passed'] = True
    except BaseException as error:
        report['error'] = repr(error)
        raise
    finally:
        report['owned_app_pids'] = [owner.process.pid for owner in HostApp.owners
                                    if owner.process is not None]
        report['all_owned_apps_exited'] = all(owner.process is None or owner.process.poll() is not None
                                              for owner in HostApp.owners)
        write(folder / 'report.json', report)
        write(arguments.report, report)


if __name__ == '__main__':
    main()
