//! Immutable source-coordinate u16 local coverage in the shared binary pool.
//! The little-endian blob is authoritative both in memory and on disk, so a
//! mask handle and its native attachment share one allocation without copies.
//!
//! At most `raw_local_limits::MAX_RAW_LOCALS` local resources, 64,000,000 samples per plane and
//! 4,096 dabs / 256 million evaluated brush pixels; the limits module's combined resource cap
//! applies. Every command rejects unknown
//! fields, including `empty` and `invert`: internally tagged Serde unit variants discard extra
//! fields, so these use empty struct variants.
use crate::job_control::{DrJobControl, JobContext};
use crate::precision_image::{admit, reserved_vec, BOOKKEEPING_BYTES};
use crate::resources::Inventory;
use crate::source_attachment::SourceBlob;
use serde_json::{json, Value};
use std::sync::Arc;

pub const MAX_RAW_LOCAL_PIXELS: u64 = 64_000_000;
pub const RAW_LOCAL_HEADER: usize = 16;
pub const MAX_RAW_LOCAL_COMMAND: usize = 1024 * 1024;
pub(crate) const PARSE_SCRATCH: u64 = 8 * BOOKKEEPING_BYTES;

#[derive(Clone)]
pub struct RawLocalMask {
    pub(crate) width: u32,
    pub(crate) height: u32,
    pub(crate) blob: SourceBlob,
}

pub(crate) fn dimensions(width: u32, height: u32) -> Result<usize, String> {
    let n = crate::precision_image::pixel_count(width, height)?;
    if n as u64 > MAX_RAW_LOCAL_PIXELS {
        return Err("local mask exceeds the 64 megapixel limit".into());
    }
    Ok(n)
}

/// Validate borrowed records before any native image or mask allocation.
pub(crate) fn header_dimensions(bytes: &[u8]) -> Result<(u32, u32), String> {
    if bytes.len() < RAW_LOCAL_HEADER || &bytes[..4] != b"RZLM" {
        return Err("local mask requires a complete RZLM header".into());
    }
    let word = |at| u32::from_le_bytes(bytes[at..at + 4].try_into().unwrap());
    if word(4) != 1 {
        return Err("unsupported local mask payload version".into());
    }
    let (w, h) = (word(8), word(12));
    dimensions(w, h)?;
    Ok((w, h))
}
pub(crate) fn validate_blob(bytes: &[u8]) -> Result<(u32, u32), String> {
    let (w, h) = header_dimensions(bytes)?;
    let n = dimensions(w, h)?;
    if bytes.len() != RAW_LOCAL_HEADER + n * 2 {
        return Err("local mask sample length differs from its dimensions".into());
    }
    Ok((w, h))
}

/// Native containers preserve unknown binary versions as opaque resources.
/// Only a known version grants permission to interpret coverage samples.
pub(crate) fn validate_stored_blob(bytes: &[u8]) -> Result<Option<(u32, u32)>, String> {
    if bytes.len() < RAW_LOCAL_HEADER || &bytes[..4] != b"RZLM" {
        return Err("local mask requires a complete RZLM header".into());
    }
    let version = u32::from_le_bytes(bytes[4..8].try_into().unwrap());
    if version != 1 {
        return Ok(None);
    }
    validate_blob(bytes).map(Some)
}

impl RawLocalMask {
    pub fn from_blob(blob: SourceBlob) -> Result<Self, String> {
        let (width, height) = validate_blob(&blob)?;
        Ok(Self {
            width,
            height,
            blob,
        })
    }
    pub fn dimensions(&self) -> (u32, u32) {
        (self.width, self.height)
    }
    pub fn encoded(&self) -> &[u8] {
        &self.blob
    }
    pub fn sample(&self, index: usize) -> Option<u16> {
        let at = index.checked_mul(2)?.checked_add(RAW_LOCAL_HEADER)?;
        let bytes = self.blob.get(at..at.checked_add(2)?)?;
        Some(u16::from_le_bytes([bytes[0], bytes[1]]))
    }
    pub(crate) fn at(&self, index: usize) -> u16 {
        let at = RAW_LOCAL_HEADER + index * 2;
        u16::from_le_bytes([self.blob[at], self.blob[at + 1]])
    }
    pub fn info(&self) -> Value {
        json!({"width":self.width,"height":self.height,"byte_length":self.blob.len(),
            "storage":"u16_le","payload_version":1,"coordinates":"source_pixel_centers_v1"})
    }
    pub(crate) fn record_resources(&self, i: &mut Inventory) {
        // Use the identical allocation/category identities as generic RBIN.
        i.object(&*self.blob, "source_attachment_structure", false);
        i.vec(&self.blob, "source_resource_encoded", false);
    }
    pub fn retained_bytes(&self) -> u64 {
        let mut i = Inventory::default();
        self.record_resources(&mut i);
        i.unique_bytes()
    }
    pub(crate) fn empty_bytes(width: u32, height: u32) -> Result<Vec<u8>, String> {
        let n = dimensions(width, height)?;
        let mut bytes = reserved_vec(RAW_LOCAL_HEADER + n * 2)?;
        bytes.extend_from_slice(b"RZLM");
        for word in [1, width, height] {
            bytes.extend_from_slice(&word.to_le_bytes());
        }
        bytes.resize(RAW_LOCAL_HEADER + n * 2, 0);
        Ok(bytes)
    }
    /// A new mask from a host-generated byte coverage plane (the Vision subject or people
    /// mask): `width * height` samples, row 0 top, 0 outside…255 inside. Sample `v` is stored
    /// as `v * 257`, the u16 of the same fraction (255 · 257 = 65535), so byte coverage keeps
    /// its exact value at the mask's native depth. `Ok(None)` when every sample is 0: a plane
    /// with no coverage is not a mask to store. `Err` for a zero or over-64-megapixel size, a
    /// sample count other than `width * height`, a refused admission or a cancelled control.
    pub fn from_coverage(
        samples: &[u8],
        width: u32,
        height: u32,
        limit: u64,
        other: u64,
        control: Option<&DrJobControl>,
    ) -> Result<Option<Self>, String> {
        let _run = control.map(DrJobControl::begin).transpose()?;
        let job = control.map_or(JobContext::NONE, JobContext::new);
        job.check()?;
        let n = dimensions(width, height)?;
        if samples.len() != n {
            return Err("local mask coverage length differs from its dimensions".into());
        }
        let scratch = (RAW_LOCAL_HEADER + n * 2) as u64 + BOOKKEEPING_BYTES;
        admit(0, scratch, other, limit)?;
        job.reserve(scratch)?;
        let mut bytes = Self::empty_bytes(width, height)?;
        let mut covered = false;
        for (input, output) in samples
            .chunks(65536)
            .zip(bytes[RAW_LOCAL_HEADER..].chunks_mut(2 * 65536))
        {
            job.check()?;
            for (sample, stored) in input.iter().zip(output.chunks_exact_mut(2)) {
                covered |= *sample != 0;
                stored.copy_from_slice(&(u16::from(*sample) * 257).to_le_bytes());
            }
        }
        job.report(1.0, 5)?;
        if !covered {
            return Ok(None);
        }
        Self::from_blob(Arc::new(bytes)).map(Some)
    }
    pub fn edit(
        prior: Option<&Self>,
        width: u32,
        height: u32,
        command: &str,
        limit: u64,
        other: u64,
        control: Option<&DrJobControl>,
    ) -> Result<Option<Self>, String> {
        let _run = control.map(DrJobControl::begin).transpose()?;
        let job = control.map_or(JobContext::NONE, JobContext::new);
        job.check()?;
        let n = dimensions(width, height)?;
        if prior.is_some_and(|p| p.dimensions() != (width, height)) {
            return Err("local mask edit dimensions differ from the captured plane".into());
        }
        if command.len() > MAX_RAW_LOCAL_COMMAND {
            return Err("local mask command exceeds 1 MiB".into());
        }
        let retained = prior.map_or(0, Self::retained_bytes);
        admit(retained, PARSE_SCRATCH, other, limit)?;
        job.reserve(PARSE_SCRATCH)?;
        let command = crate::raw_local_coverage::Command::parse(command, width, height)?;
        let scratch = PARSE_SCRATCH + n as u64 * (if command.brush() { 6 } else { 2 }) + 64;
        admit(retained, scratch, other, limit)?;
        job.reserve(scratch)?;
        let bytes = command.apply(prior, width, height, job)?;
        if let Some(prior) = prior {
            let mut equal = true;
            for (a, b) in bytes.chunks(65536).zip(prior.encoded().chunks(65536)) {
                job.check()?;
                equal &= a == b;
            }
            if equal {
                job.report(1.0, 5)?;
                return Ok(None);
            }
        }
        job.report(1.0, 5)?;
        Self::from_blob(Arc::new(bytes)).map(Some)
    }
    /// Stage the complete binary payload before publishing caller bytes.
    pub fn copy(
        &self,
        output: &mut [u8],
        limit: u64,
        other: u64,
        control: Option<&DrJobControl>,
    ) -> Result<(), String> {
        let _run = control.map(DrJobControl::begin).transpose()?;
        let job = control.map_or(JobContext::NONE, JobContext::new);
        job.check()?;
        if output.len() != self.encoded().len() {
            return Err("local mask output length differs from its payload".into());
        }
        let scratch = output.len() as u64 + BOOKKEEPING_BYTES;
        admit(
            self.retained_bytes(),
            scratch + output.len() as u64,
            other,
            limit,
        )?;
        job.reserve(scratch)?;
        let mut staged = reserved_vec(output.len())?;
        for bytes in self.encoded().chunks(65536) {
            job.check()?;
            staged.extend_from_slice(bytes);
        }
        job.report(1.0, 5)?;
        output.copy_from_slice(&staged);
        Ok(())
    }
}
