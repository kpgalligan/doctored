/// `(K, A/M)` of the slider `vibrance` (a fraction in −1…1) for a linear
/// pixel of chroma `chroma` = `(M − m)/M` and maximum `max`, both in [0, 1],
/// whose linear hexcone hue is `hue` in degrees (`None` on a grey). At 0 it is
/// the identity `(1, 1)`.
pub(crate) fn gain_and_anchor(
    vibrance: f64,
    chroma: f64,
    max: f64,
    hue: Option<f64>,
) -> (f64, f64) {
    if vibrance == 0.0 {
        return (1.0, 1.0);
    }
    let (gain, anchor) = if vibrance < 0.0 {
        (&DOWN_K, &DOWN_A)
    } else {
        (&UP_K, &UP_A)
    };
    let cell = Cell::of(chroma, max);
    let mut k = 0.0;
    let mut a = 0.0;
    for (knot, weight) in slider_weights((vibrance.abs() * 100.0).min(100.0)) {
        k += weight * cell.read(&gain[knot]);
        a += weight * cell.read(&anchor[knot]);
    }
    let p = if vibrance > 0.0 { skin(hue) } else { 1.0 };
    ((1.0 + p * k).max(0.0), 1.0 + p * a)
}

/// The slider knots straddling `slider` (the slider's units, 0…100) and their
/// weights; the identity knot at 0 carries no table, so below the first knot
/// the second slot carries weight 0. A fixed pair, not a `Vec`: this runs per
/// pixel.
fn slider_weights(slider: f64) -> [(usize, f64); 2] {
    let mut lo = 0.0;
    for (i, &hi) in SLIDER_KNOTS.iter().enumerate() {
        if slider <= hi {
            let f = (slider - lo) / (hi - lo);
            return match i {
                0 => [(0, f), (0, 0.0)],
                _ => [(i - 1, 1.0 - f), (i, f)],
            };
        }
        lo = hi;
    }
    [(SLIDER_KNOTS.len() - 1, 1.0), (SLIDER_KNOTS.len() - 1, 0.0)]
}

