//! The Vibrance slider's law (#2), the numbers `adjust_color`'s Vibrance
//! stage runs on: the gain `K` and anchor share `A/M`, fitted to Photoshop
//! 26.10.0, as tables over a pixel's linear chroma and maximum. A kernel
//! module: plain numbers and free functions, no profile and no document.
//!
//! The stage moves each LINEAR component `c` of a pixel with maximum `M`,
//! minimum `m` and chroma `S = (M − m)/M` to `clamp01(A + (c − A)·K)`, `A =
//! M·(A/M)`: one anchor and one gain for the three components, so the pixel's
//! hexcone hue in linear light is held, as the takes measured Photoshop
//! holding it (`adjust_color`'s module doc). `K` and `A/M` are member V3t-P of
//! `scripts/photoshop-probe/adjust_arith_578_take.py` (receipt
//! `adjust-arith-578/take1`; its docstring fixes the family, the fit and the
//! judge), copied from the runner's `adjust_arith_578_fitted.json`:
//!
//! * per sign of the slider, a table of `K − 1` and of `A/M − 1` on the knots
//!   `S ∈ {0, 1/8, …, 1}` × `√M ∈ {0, 1/4, …, 1}`, read bilinearly in `S` and
//!   `√M` (the square root spends the knots where the measured gain changes
//!   fastest, in the shadows);
//! * at the slider knots `|v| ∈ {10, 25, 50, 75, 100}` (the slider's units),
//!   linear in `|v|` between them, the identity (`K = 1`, `A/M = 1`) at 0;
//! * above 0, both deviations times the skin term `p = 1 − 0.4·max(0, 1 −
//!   d(h, 5°)/55°)` on the hue `h` of the linear pixel (1 on a grey);
//! * `K` clamped at 0.
//!
//! The `S = 0` row of `A/M` is pinned to the identity, so `A/M → 1` as a pixel
//! nears grey and a near-grey pixel moves continuously to an exact grey's
//! identity (`A = M = c`). The tables are least squares on Photoshop's own
//! per-pixel gain and anchor (v1x takes 1-4), then one minimax pass per knot;
//! a knot no sample reached stays at the identity, which is why some corners
//! (`√M = 0`, the darkest column) read as small irregular numbers: they are
//! weighted by nothing a real pixel there can tell apart.

