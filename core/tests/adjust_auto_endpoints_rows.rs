//! Auto Tone takes 6 and 7 (round 2,
//! `scripts/photoshop-probe/adjust_v1x_round2.py`,
//! `doctored-fixtures/photoshop/adjust-parity-v1x/take{3,4}/auto438`): the
//! designed pictures and Photoshop 26.10.0's `levl` rows, against the shipped
//! Auto Tone rule (`adjust_auto_endpoints`' module doc and oracle).
//!
//! Round 2 fitted a white coupling and a black gap placement on take 6 and
//! judged them on take 7's fresh pictures; neither end was measurably closer
//! than today's there (the runner's docstring holds every residual), so
//! today's rule stays and these rows hold it to its own take-6 and take-7
//! residuals (max codes, both declared before this file):
//!
//! * take 6 (8 bits): white 13, black 13;
//! * take 7: white 47 at 8 bits and 20 at 16, black 20 and 9.
//!
//! The pictures are the runner's `fixture()` draws spelled out: E1-E5 (fat
//! head bins, decorrelated heads), F1-F4 (short dark tails, a gap, a first
//! body bin of a declared mass; F4 is F1 on a 160 x 100 canvas) and R1-R8
//! (`random.Random(4480 + i)`), each tail ending with its first body bin.
//! The two-clip Kab3 rows have no single-clip Doctored form and are left
//! out.

use crate::adjust_auto_endpoints::{oracle, ours16, ours8, scope, wide, Fixture, G1};

/// Take 6's and take 7's residuals of today's rule (module doc): (take,
/// depth) -> (white, black) in codes.
fn bound(take: u32, depth: u32) -> (f64, f64) {
    match (take, depth) {
        (6, _) => (13.0, 13.0),
        (7, 8) => (47.0, 20.0),
        _ => (20.0, 9.0),
    }
}

/// One row: the picture (an index of [`PICTURES`], or [`G1_PIC`]), its
/// depth and case (`true` = `clip`, the photo over white), the clip and
/// Photoshop's `levl` (black, white) per channel.
type TakeRow = (usize, u32, bool, f64, [(i64, i64); 3]);

/// Take 3's G1 (take 6's A1 repeat).
const G1_PIC: usize = 17;

fn picture(index: usize) -> &'static Fixture {
    if index == G1_PIC {
        &G1
    } else {
        &PICTURES[index]
    }
}

#[test]
fn eight_bit_auto_tone_is_the_declared_rule_on_round_twos_pictures() {
    for (index, f) in PICTURES.iter().enumerate() {
        for clip_case in [false, true] {
            let pixels = scope(f, clip_case);
            for clip in [0.0f32, 0.001, 0.003, 0.005] {
                let got = ours8(&pixels, clip);
                let want = oracle(&wide(&pixels), 255, f64::from(clip), 1.0);
                for c in 0..3 {
                    let code = |v: f64| (v * 255.0).round() as i64;
                    assert_eq!(
                        (code(got[c].0), code(got[c].1)),
                        (code(want[c].0), code(want[c].1)),
                        "picture {index} clip-case {clip_case}, clip {clip}, channel {c}"
                    );
                }
            }
        }
    }
}

#[test]
fn photoshop_rows_of_takes_six_and_seven_hold_todays_residuals() {
    for (take, rows) in [(6, &TAKE6_ROWS[..]), (7, &TAKE7_ROWS[..])] {
        for &(index, depth, clip_case, clip, photoshop) in rows {
            let pixels = scope(picture(index), clip_case);
            let got = if depth == 8 {
                ours8(&pixels, clip as f32)
            } else {
                let wide16: Vec<[u16; 3]> = pixels
                    .iter()
                    .map(|p| p.map(|v| u16::from(v) * 257))
                    .collect();
                ours16(&wide16, clip)
            };
            let (white_bound, black_bound) = bound(take, depth);
            for (c, ((black, white), (ps_black, ps_white))) in got.iter().zip(photoshop).enumerate()
            {
                let label = format!(
                    "take {take} picture {index} depth {depth} clip-case {clip_case} clip {clip} \
                     channel {c}"
                );
                assert!(
                    ((black * 255.0).round() - ps_black as f64).abs() <= black_bound,
                    "{label}: black {black} vs {ps_black}"
                );
                assert!(
                    ((white * 255.0).round() - ps_white as f64).abs() <= white_bound,
                    "{label}: white {white} vs {ps_white}"
                );
            }
        }
    }
}

